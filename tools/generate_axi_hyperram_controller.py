"""Generate the synthesizable same-clock AXI/HyperBus startup assembly."""
import hashlib
import json
from pathlib import Path
from generate_bidirectional_application import ports

from rtl_paths import source_path, source_relative


def main():
    root=Path(__file__).resolve().parents[1];sha=lambda p:hashlib.sha256(p.read_bytes()).hexdigest()
    names=('axi_hyperram_bridge','hyperram_transaction_engine','hyperram_startup')
    paths={n:source_path(root, Path('rtl') / (n+'.v'))for n in names}
    fp,ep,sp=(ports(paths[n].read_text(),n)for n in names)
    public=[(d,w.replace('ADDR_WIDTH','23'),n)for d,w,n in fp if n in('clk','rst')or n.startswith('s_axi_')]
    public +=[(d,w,n)for d,w,n in ep if n.startswith('phy_')]
    public +=[(d,w,n)for d,w,n in sp if n in('power_good','phy_ready','contents_reload_ack','fabric_reset','phy_reset_n',
        'memory_ready','startup_fault','startup_detail','startup_phase','contents_lost','device_id0','device_id1','config_readback')]
    public +=[('output','','idle'),('output','[7:0]','memory_detail')]
    assert len({n for _,_,n in public})==len(public)
    lines=['`timescale 1ns/1ps','`default_nettype none',
        '// Generated by tools/generate_axi_hyperram_controller.py.',
        '// All interfaces use the memory word clock; this is not a pin PHY or CDC.',
        '// Wire fabric_reset to the AXI master reset too; supply/PHY loss aborts the fabric.',
        'module axi_hyperram_controller #(',
        '    parameter MEMORY_CLOCK_HZ=200000000,CONFIG_LATENCY=7,FIXED_LATENCY=1',')(']
    lines +=[f'    {d} wire {w} {n}{","if i+1<len(public)else""}'for i,(d,w,n)in enumerate(public)]
    lines +=[');','wire frontend_idle,engine_idle,engine_reset,engine_enable;',
        'wire [3:0] engine_latency;','wire engine_fixed_latency;',
        'assign idle=memory_ready&&frontend_idle&&engine_idle;']
    for _,w,n in fp:
        if n.startswith('hb_'):lines.append(f'wire {w.replace("ADDR_WIDTH","23")} {n};')
    for _,w,n in sp:
        if n.startswith('init_'):lines.append(f'wire {w} {n};')
    for _,w,n in ep:
        if n.startswith(('cmd_','rsp_')):lines.append(f'wire {w} {n};')
    lines +=['axi_hyperram_bridge #(.ADDR_WIDTH(23)) frontend(',
        ',\n'.join(f'    .{n}('+('fabric_reset'if n=='rst'else'frontend_idle'if n=='idle'else n)+')'for _,_,n in fp),');']
    for n in ('valid','write','address','data'):
        lines.append(f'assign cmd_{n}=memory_ready?hb_cmd_{n}:init_cmd_{n};')
    lines +=["assign cmd_register=!memory_ready;","assign cmd_bytes=memory_ready?hb_cmd_bytes:7'd2;",
        "assign cmd_strobes=memory_ready?hb_cmd_strobes:64'd3;",
        'assign hb_cmd_ready=memory_ready&&cmd_ready;',
        'assign init_cmd_ready=!memory_ready&&cmd_ready;',
        'assign rsp_ready=memory_ready?hb_rsp_ready:init_rsp_ready;']
    for n in ('valid','data','error'):
        value=f'rsp_{n}'if n!='valid'else'memory_ready&&rsp_valid'
        lines.append(f'assign hb_rsp_{n}={value};')
        value=f'rsp_{n}'if n!='valid'else'!memory_ready&&rsp_valid'
        lines.append(f'assign init_rsp_{n}={value};')
    lines +=['assign init_rsp_detail=rsp_detail;','assign memory_detail=rsp_detail;',
        'hyperram_startup #(.MEMORY_CLOCK_HZ(MEMORY_CLOCK_HZ),.CONFIG_LATENCY(CONFIG_LATENCY),.FIXED_LATENCY(FIXED_LATENCY)) startup(',
        ',\n'.join(f'    .{n}('+('frontend_idle&&engine_idle'if n=='transactions_idle'else n)+')'for _,_,n in sp),');']
    remap={'rst':'engine_reset','enable':'engine_enable','cfg_latency':'engine_latency','cfg_fixed_latency':'engine_fixed_latency','idle':'engine_idle'}
    lines +=['hyperram_transaction_engine #(.MEMORY_CLOCK_HZ(MEMORY_CLOCK_HZ)) engine(',
        ',\n'.join(f'    .{n}({remap.get(n,n)})'for _,_,n in ep),');','endmodule','`default_nettype wire','']
    target=source_path(root, 'rtl/axi_hyperram_controller.v');target.write_text('\n'.join(lines))
    result=dict(generator_sha256=sha(Path(__file__)),input_sha256={source_relative(p, root).as_posix():sha(p)for p in paths.values()},
        port_parser_sha256=sha(root/'tools/generate_bidirectional_application.py'),output_sha256=sha(target),
        same_clock_assembly=True,pin_level_phy_present=False,full_system_complete=False)
    folder=root/'build/hyperram-startup';folder.mkdir(parents=True,exist_ok=True)
    (folder/'generation.json').write_text(json.dumps(result,indent=2)+'\n');print(json.dumps(result))


if __name__=='__main__':main()
